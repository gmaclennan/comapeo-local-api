#!/usr/bin/env node
import * as fs from 'node:fs/promises'
import * as os from 'node:os'
import * as path from 'node:path'
import * as readline from 'node:readline'
import { parseArgs } from 'node:util'

import { createLocalApiServer } from '../server.ts'
import { DevCommands } from './commands.ts'
import { createDevManager } from './manager.ts'
import { seedProject } from './seed.ts'

const USAGE = `Usage: node src/dev/cli.ts [options]

Serves generated CoMapeo test projects on the local API, from an in-memory
core, until interrupted. Prints "READY <discovery file path>" when ready.

Options:
  --discovery-dir <dir>   where to write comapeo-local-api.json
                          (default: <tmp>/comapeo-local-api-dev)
  --observations <n>      observations in the first project (default 300)
  --tracks <n>            tracks in the first project (default 5)
  --photos <n>            photos in the first project (default 40)
  --projects <1|2>        number of projects (default 2)
  --seed <n>              random seed (default 1)
  --help

While running, type "help" on stdin for commands that change data, or
"quit" to stop.`

function count(
	value: string | undefined,
	name: string,
	fallback: number,
): number {
	if (value === undefined) return fallback
	const n = Number(value)
	if (!Number.isInteger(n) || n < 0)
		throw new Error(`--${name} must be a whole number`)
	return n
}

async function main() {
	const { values } = parseArgs({
		options: {
			'discovery-dir': { type: 'string' },
			observations: { type: 'string' },
			tracks: { type: 'string' },
			photos: { type: 'string' },
			projects: { type: 'string' },
			seed: { type: 'string' },
			help: { type: 'boolean' },
		},
	})
	if (values.help) {
		console.log(USAGE)
		return
	}
	const discoveryDir = path.resolve(
		values['discovery-dir'] ?? path.join(os.tmpdir(), 'comapeo-local-api-dev'),
	)
	const seed = count(values.seed, 'seed', 1)
	const projectCount = Math.min(
		2,
		Math.max(1, count(values.projects, 'projects', 2)),
	)
	const log = (message: string) => process.stderr.write(message + '\n')
	const first = {
		observations: count(values.observations, 'observations', 300),
		tracks: count(values.tracks, 'tracks', 5),
		photos: count(values.photos, 'photos', 40),
	}

	const dev = await createDevManager({ deviceName: 'CoMapeo dev server' })
	const mediaDir = await fs.mkdtemp(
		path.join(os.tmpdir(), 'comapeo-dev-media-'),
	)
	const server = createLocalApiServer({
		manager: dev.manager,
		discoveryDir,
		app: { name: 'CoMapeo local API dev server', version: '0.0.0-dev' },
	})

	let stopping = false
	const stop = async (code: number) => {
		if (stopping) return
		stopping = true
		await server.close().catch(() => {})
		await dev.close().catch(() => {})
		await fs.rm(mediaDir, { recursive: true, force: true })
		process.exit(code)
	}
	process.once('SIGINT', () => stop(0))
	process.once('SIGTERM', () => stop(0))

	try {
		const specs = [
			{
				name: 'Tapajós monitoring (test data)',
				projectColor: '#1163DE',
				projectDescription: 'Generated by the CoMapeo local API dev command',
				...first,
				audio: 3,
			},
			{
				name: 'Small test project',
				projectColor: '#2D9905',
				projectDescription: 'A second, smaller generated project',
				observations: 20,
				tracks: 1,
				photos: 3,
				audio: 1,
			},
		].slice(0, projectCount)

		const projects = []
		for (const [i, spec] of specs.entries()) {
			const { name, projectColor, projectDescription } = spec
			const projectId = await dev.manager.createProject({
				name,
				projectColor,
				projectDescription,
			})
			const project = await dev.manager.getProject(projectId)
			log(`Seeding "${name}"…`)
			const summary = await seedProject(project, {
				...spec,
				seed: seed + i,
				mediaDir,
			})
			log(`  ${projectId}: ${JSON.stringify(summary)}`)
			projects.push({ projectId, project })
		}

		const { discoveryFilePath } = await server.listen()
		console.log(`READY ${discoveryFilePath}`)

		const commands = new DevCommands(projects, seed)
		const rl = readline.createInterface({ input: process.stdin })
		rl.on('line', (line) => {
			if (line.trim() === 'help') {
				log(DevCommands.HELP)
				return
			}
			if (line.trim() === 'quit') {
				void stop(0)
				return
			}
			commands.run(line).then(
				(result) => result && console.log(`OK ${JSON.stringify(result)}`),
				(err: unknown) =>
					console.log(
						`ERROR ${err instanceof Error ? err.message : String(err)}`,
					),
			)
		})
		log('Type "help" for commands that change data; Ctrl-C to stop.')
	} catch (err) {
		log(err instanceof Error ? (err.stack ?? err.message) : String(err))
		await stop(1)
	}
}

main().catch((err: unknown) => {
	process.stderr.write(String(err instanceof Error ? err.message : err) + '\n')
	process.exit(1)
})
